// Writes server/internal/api/sharecard_countries_i18n.go: the names of the countries the share pictures know, in the
// pictures' languages, from the same Unicode data the dashboard's Intl.DisplayNames uses. The languages are the
// dashboard's own (dashboard/src/i18n/languages.ts). Run: node scripts/gen-country-names.mjs
// With --check it only compares and exits 1 when the file is out of date.
import { readFileSync, writeFileSync } from 'node:fs'

const root = new URL('../', import.meta.url)
const langs = [...readFileSync(new URL('dashboard/src/i18n/languages.ts', root), 'utf8').matchAll(/code: '(\w\w)'/g)].map((m) => m[1]).filter((c) => c !== 'en')
const countries = readFileSync(new URL('server/internal/api/sharecard_countries.go', root), 'utf8')
const codes = [...countries.matchAll(/^\t"([A-Z]{2})":/gm)].map((m) => m[1])

let out = '// Code generated by scripts/gen-country-names.mjs; DO NOT EDIT.\n\npackage api\n\n// countryNamesIn are the countries\' names in each language but English, by language and code.\nvar countryNamesIn = map[string]map[string]string{\n'
for (const lang of langs) {
  const names = new Intl.DisplayNames([lang], { type: 'region' })
  out += `\t${JSON.stringify(lang)}: {\n`
  for (const code of codes) {
    const name = names.of(code)
    if (name && name !== code) out += `\t\t${JSON.stringify(code)}: ${JSON.stringify(name)},\n`
  }
  out += '\t},\n'
}
out += '}\n'

const file = new URL('server/internal/api/sharecard_countries_i18n.go', root)
if (process.argv.includes('--check')) {
  let have = ''
  try {
    have = readFileSync(file, 'utf8')
  } catch {
    /* missing */
  }
  if (have !== out) {
    console.error('sharecard_countries_i18n.go is out of date: run node scripts/gen-country-names.mjs')
    process.exit(1)
  }
} else {
  writeFileSync(file, out)
}
