/** A word in the middle of a sentence: "Canales" becomes "canales", "IA" and "OS" stay as they are. */
const lowerFirst = (s: string) => (/^\p{Lu}\p{Ll}/u.test(s) ? s.charAt(0).toLowerCase() + s.slice(1) : s)

/** A share as a percentage: one decimal under 10 %, none above. */
const pc = (x: number) => pct(x, x > 0 && x < 0.1 ? 1 : 0)

/** ", ni en los 3 scripts que carga", said properly for none and one. */
function scriptsRead(n: number): string {
  if (n === 0) return ''
  if (n === 1) return ', ni en el único script que carga'
  return `, ni en los ${n} scripts que carga`
}

