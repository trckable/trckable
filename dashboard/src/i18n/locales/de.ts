/** ", und auch nicht in den 3 Skripten, die sie lädt", said properly for none and one. */
function scriptsRead(n: number): string {
  if (n === 0) return ''
  if (n === 1) return ', und auch nicht in dem einen Skript, das sie lädt'
  return `, und auch nicht in den ${n} Skripten, die sie lädt`
}

