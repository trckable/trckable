// Turns the world atlas into the globe's two small tables, once, at build time: a coarse land mask (the dots) and
// one centre point per country. No map tiles, no network: the dashboard bundles the result.
//
// Run with `npm run build:globe` after changing anything here.
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const land = require('world-atlas/land-110m.json')
const countries50 = require('world-atlas/countries-50m.json')
const { feature } = require('topojson-client')
const iso = require('iso-3166-1')

const STEP = 2.5 // degrees between dot rows
const polysOf = (g) => (g.type === 'Polygon' ? [g.coordinates] : g.coordinates)

function inRing(x, y, ring) {
  let c = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i]
    const [xj, yj] = ring[j]
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c
  }
  return c
}
const inPoly = (x, y, rings) => rings.reduce((n, r) => n + (inRing(x, y, r) ? 1 : 0), 0) % 2 === 1

const polys = feature(land, land.objects.land).features.flatMap((f) => polysOf(f.geometry))
const boxes = polys.map((p) => {
  const xs = p[0].map((c) => c[0])
  const ys = p[0].map((c) => c[1])
  return [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)]
})
const isLand = (lon, lat) => polys.some((p, i) => lon >= boxes[i][0] && lon <= boxes[i][1] && lat >= boxes[i][2] && lat <= boxes[i][3] && inPoly(lon, lat, p))

// Rows run north to south; a row has fewer dots nearer the poles so they sit evenly. Land is stored as runs: start, length.
const rows = []
for (let lat = 84 - STEP / 2; lat > -58; lat -= STEP) {
  const cols = Math.max(1, Math.round((360 / STEP) * Math.cos((lat * Math.PI) / 180)))
  const runs = []
  let from = -1
  for (let j = 0; j <= cols; j++) {
    const on = j < cols && isLand(-180 + ((j + 0.5) * 360) / cols, lat)
    if (on && from < 0) from = j
    if (!on && from >= 0) {
      runs.push(from, j - from)
      from = -1
    }
  }
  rows.push(runs)
}

// One point per country: the middle of its largest piece, to a whole degree.
const ring = (r) => {
  let a = 0
  let cx = 0
  let cy = 0
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
    const f = r[j][0] * r[i][1] - r[i][0] * r[j][1]
    a += f
    cx += (r[j][0] + r[i][0]) * f
    cy += (r[j][1] + r[i][1]) * f
  }
  return { a: Math.abs(a / 2), x: cx / (3 * a), y: cy / (3 * a) }
}
const places = {}
for (const f of feature(countries50, countries50.objects.countries).features) {
  const rec = iso.whereNumeric(String(f.id).padStart(3, '0'))
  const code = rec?.alpha2 ?? (f.properties.name === 'Kosovo' ? 'XK' : null)
  if (!code) continue
  const best = polysOf(f.geometry).map((p) => ring(p[0])).sort((a, b) => b.a - a.a)[0]
  if (best && Number.isFinite(best.x)) places[code] = [Math.round(best.y), Math.round(best.x)]
}
// Small states the 50m atlas leaves out.
Object.assign(places, { SG: [1, 104], MT: [36, 14], MC: [44, 7], SM: [44, 12], VA: [42, 12], LI: [47, 9], AD: [43, 2], BH: [26, 50], MV: [4, 73], HK: [22, 114], MO: [22, 114], BB: [13, -59], MU: [-20, 58] })

const body = `// Generated by scripts/build-globe.mjs from world-atlas. Do not edit.
// LAND: dot rows from ${84 - STEP / 2}° north in ${STEP}° steps, each row a list of land runs (first dot, dot count).
export const STEP = ${STEP}
export const LAND: number[][] = ${JSON.stringify(rows)}
// PLACES: one [lat, lon] per country, the middle of its largest piece. The server stores a country and a city name, never coordinates.
export const PLACES: Record<string, [number, number]> = ${JSON.stringify(places)}
`
writeFileSync(new URL('../src/v2/live/globe/globeData.ts', import.meta.url), body)
console.log(`${rows.length} rows, ${Object.keys(places).length} places, ${(body.length / 1024).toFixed(1)} KB raw`)
